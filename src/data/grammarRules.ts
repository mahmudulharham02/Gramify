export function getRuleOfTheDay(dayOfMonth?: number): GrammarRule {
  const day = dayOfMonth !== undefined ? dayOfMonth : new Date().getDate();
  const index = Math.abs((day - 1) % GRAMMAR_RULES_BANK.length);
  return GRAMMAR_RULES_BANK[index] || GRAMMAR_RULES_BANK[0];
}
